    public void setVisible(boolean visible) {
        super.setVisible(visible);
        if (visible) {
            cargarTablaMovimientos(); // ✅ se ejecuta con el usuario ya logueado
        }
    }

    public void cargarTablaMovimientos() {
        String usuario = usuarioSer.getUsuario();
        System.out.println(">>> Usuario en tabla: " + usuario); // debug temporal

        if (usuario == null || usuario.isEmpty()) {
            return; // silencioso, sin JOptionPane
        }

        List<Document> lista = servicioMo.obtenerMovimientosPorUsuario(usuario);
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        for (Document doc : lista) {
            modelo.addRow(new Object[]{
                doc.getObjectId("_id").toString(),
                doc.getString("tipoDeMovimiento"),
                ((Number) doc.get("monto")).doubleValue(),
                doc.getString("descripcion")
            });
        }
    }
