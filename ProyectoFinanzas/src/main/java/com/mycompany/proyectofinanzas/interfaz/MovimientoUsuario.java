    private void editarMovimientoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editarMovimientoActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un movimiento");
            return;
        }

        String id = jTable1.getValueAt(fila, 0).toString();

        String tipo = jTable1.getValueAt(fila, 1).toString();
        double monto = (Double) jTable1.getValueAt(fila, 2);
        String descripcion = jTable1.getValueAt(fila, 3).toString();

        // Ejemplo simple (puedes mejorar con inputs)
        servicioMo.actualizarMovimiento(id, tipo, monto, descripcion);

        cargarTablaMovimientos();
    }//GEN-LAST:event_editarMovimientoActionPerformed

    private void eliminarMovimientoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_eliminarMovimientoActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un movimiento");
            return;
        }

        String id = jTable1.getValueAt(fila, 0).toString();

        servicioMo.eliminarMovimiento(id);

        cargarTablaMovimientos();
    }//GEN-LAST:event_eliminarMovimientoActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();

        if (fila != -1) {
            // Obtener datos actuales desde la tabla
            String id = jTable1.getValueAt(fila, 0).toString();
            String tipo = jTable1.getValueAt(fila, 1).toString();
            Double monto = (Double) jTable1.getValueAt(fila, 2);
            String descripcion = jTable1.getValueAt(fila, 3).toString();

            //Pedir nuevos datos (con valores actuales por defecto)
            String nuevoTipo = JOptionPane.showInputDialog("Nuevo tipo:", tipo);
            String nuevoMontoStr = JOptionPane.showInputDialog("Nuevo monto:", monto);
            String nuevaDescripcion = JOptionPane.showInputDialog("Nueva descripción:", descripcion);

            // Convertir monto
            double nuevoMonto = Double.parseDouble(nuevoMontoStr);

            // Actualizar en BD
            servicioMo.actualizarMovimiento(id, nuevoTipo, nuevoMonto, nuevaDescripcion);

            // Recargar tabla
            cargarTablaMovimientos();
        }
    }//GEN-LAST:event_jTable1MouseClicked


